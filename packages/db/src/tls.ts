/**
 * node-postgres options for a connection string. Supabase hosts get full
 * verification against the pinned root; any other host keeps whatever its
 * URL asks for (local Postgres in docker-compose has no TLS at all).
 */
export function pgOptions(url: string): { connectionString: string; ssl?: { ca: string; rejectUnauthorized: true } } {
  const u = new URL(url)
  if (!u.hostname.endsWith(".supabase.com") && !u.hostname.endsWith(".supabase.co")) {
    return { connectionString: url }
  }
  // sslmode in the URL would override the ssl object below; drop it.
  u.searchParams.delete("sslmode")
  u.searchParams.delete("supa")
  return { connectionString: u.toString(), ssl: { ca: SUPABASE_ROOT_CA, rejectUnauthorized: true } }
}
